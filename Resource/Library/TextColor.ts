 /* The value must have compatibility with MITextColor class */
const enum TextColor {
	black      = 0x0,
        red        = 0x1,
        green      = 0x2,
        yellow     = 0x3,
        blue       = 0x4,
        magenta    = 0x5,
        cyan       = 0x6,
        white      = 0x7
 } ;

